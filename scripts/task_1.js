// якщо ділиться  без остачі і на 3, і на 5 - виводить в консоль 'fizzbuzz'.

function fizzBuzz(num) {
    let result = "";
    for (let i = 1; i <= num; i++) {
        if (i % 3 === 0) {
            result +=  `for ${i} the result is: fizz \n`;
        } else if (i % 5 === 0) {
            result +=  `for ${i} the result is: buzz \n`;
        } else if (i % 3 === 0 && i % 5 === 0) {
            result +=  `for ${i} the result is: fifizzbuzzzz \n`;
        } else {
            result += `the ${i} isn't defined \n`;
        }
    }
    return result;
}
