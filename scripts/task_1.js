/*Створи функцію calculate(a, b, operator).
  Параметр operator може містити:
  - "+";
  - "-";
  - "*";
  - "/".

  Функція повинна виконувати відповідну операцію через switch.
  Особливі випадки:
  - якщо під час ділення b дорівнює 0, поверни "Cannot divide by zero";
  - якщо передано невідомий оператор, поверни "Unknown operator".
  */
function calculate(a, b, operator) {

    switch (operator) {
        case '+':
            return a + b;
        case '-':
            return a - b;
        case '*':
            return a * b;
        case '/':
            return b === 0 ? "Cannot divide by zero" : a / b;
        default:
            return "Unknown operator";
    }
}

