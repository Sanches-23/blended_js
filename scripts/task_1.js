//Створи `reverseText(text)`, яка проходить від останнього символу до першого і повертає перевернутий рядок. Перевір `'browser'`.

function reverseText(text) {
    let revText = '';
    for (let i = text.length - 1; i >= 0; i--) {
        revText += text[i];
    }
    return revText;
}

